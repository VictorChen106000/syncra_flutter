/// Id of the [JobsBlock] currently shown as a full-screen results takeover, or
/// null when the chat is in its normal conversational layout. Set when the
/// agent returns a fresh batch of roles; cleared when the user dismisses.
final jobResultsFocusProvider = StateProvider<String?>((ref) => null);

/// Full-screen "generative UI" presentation of a job search: the agent's
/// message sits on top, every role below as a full-width card, and none of the
/// chat chrome (composer, scrims, history) — so the user reads results as a
/// page, not a cramped rail behind the input bar. Dismissing returns to the
/// chat, where the same roles remain in the transcript.
class JobResultsTakeover extends StatelessWidget {
  const JobResultsTakeover({
    super.key,
    required this.jobs,
    required this.intro,
    required this.onClose,
  });

  final List<Job> jobs;

  /// The agent's prose for this turn — shown on top as its message.
  final String intro;
  final VoidCallback onClose;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    return Material(
      color: brand.bg,
      child: SafeArea(
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            // Grabber — signals this results page sits over the chat and can be
            // dismissed back to it.
            Center(
              child: Container(
                width: 38,
                height: 4,
                margin: const EdgeInsets.only(top: 10, bottom: 2),
                decoration: BoxDecoration(
                  color: brand.border,
                  borderRadius: BorderRadius.circular(99),
                ),
              ),
            ),
            _Header(intro: intro, count: jobs.length, onClose: onClose),
            Expanded(
              child: ListView.separated(
                physics: const BouncingScrollPhysics(),
                padding: const EdgeInsets.fromLTRB(20, 4, 20, 40),
                itemCount: jobs.length,
                separatorBuilder: (_, _) => const SizedBox(height: 12),
                itemBuilder: (context, i) => _TakeoverJobCard(job: jobs[i])
                    .animate(delay: (i * 55).ms)
                    .fadeIn(duration: 320.ms)
                    .moveY(begin: 14, end: 0, curve: Curves.easeOutCubic),
              ),
            ),
          ],
        ),
      ),
    ).animate().fadeIn(duration: 200.ms);
  }
}

class _Header extends StatelessWidget {
  const _Header({
    required this.intro,
    required this.count,
    required this.onClose,
  });

  final String intro;
  final int count;
  final VoidCallback onClose;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    final message = intro.trim().isNotEmpty
        ? intro.trim()
        : 'Here are the roles I found for you.';
    return Padding(
      padding: const EdgeInsets.fromLTRB(20, 12, 20, 16),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              // The orb is Syncra's signature — its presence here signals this
              // page was generated by the agent.
              const GooeyOrb(size: 30),
              const SizedBox(width: 10),
              Text(
                'SYNCRA',
                style: TextStyle(
                  fontSize: 11,
                  fontWeight: FontWeight.w900,
                  letterSpacing: 1.6,
                  color: brand.textMuted,
                ),
              ),
              const Spacer(),
              _CloseButton(onTap: onClose),
            ],
          ),
          const SizedBox(height: 16),
          // The agent's message, on top of the results.
          Text(
            message,
            style: TextStyle(
              fontSize: 19,
              fontWeight: FontWeight.w700,
              letterSpacing: -0.4,
              height: 1.35,
              color: brand.ink,
            ),
          ).animate().fadeIn(duration: 300.ms).moveY(
                begin: 8,
                end: 0,
                duration: 300.ms,
                curve: Curves.easeOutCubic,
              ),
          const SizedBox(height: 12),
          Text(
            '${count == 1 ? '1 ROLE' : '$count ROLES'} · TAP A CARD FOR OPTIONS',
            style: TextStyle(
              fontSize: 10.5,
              fontWeight: FontWeight.w800,
              letterSpacing: 1.3,
              color: brand.textSoft,
            ),
          ),
        ],
      ),
    );
  }
}

class _CloseButton extends StatelessWidget {
  const _CloseButton({required this.onTap});

  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    return Semantics(
      button: true,
      label: 'Close results',
      child: Material(
        color: brand.surfaceMuted,
        shape: const CircleBorder(),
        child: InkWell(
          onTap: onTap,
          customBorder: const CircleBorder(),
          child: SizedBox(
            width: 36,
            height: 36,
            child: Icon(Icons.close_rounded, size: 18, color: brand.ink),
          ),
        ),
      ),
    );
  }
}

/// A full-width role card for the takeover list — richer than the chat rail's
/// compact card. Tapping opens the shared [JobActionSheet] (save, draft, share,
/// dismiss), so every action stays available without leaving the page.
class _TakeoverJobCard extends StatelessWidget {
  const _TakeoverJobCard({required this.job});

  final Job job;

  @override
  Widget build(BuildContext context) {
    final brand = context.brand;
    // The strongest bucket gets a filled accent pill so the best fits pop;
    // weaker buckets stay quiet with a dot + label.
    final (matchColor, matchLabel, prominent) = switch (job.category) {
      JobCategory.ready => (brand.accent, 'ALL MATCH', true),
      JobCategory.inputNeeded => (brand.textMuted, 'SEVERAL MATCH', false),
      JobCategory.exploration => (brand.textSoft, 'NO MATCH', false),
    };
    final subtitle = [
      if (job.company.isNotEmpty) job.company,
      if (job.salary.isNotEmpty) job.salary,
      if (job.location.isNotEmpty) job.location,
    ].join('   ·   ');
    final why = job.agentJustification.trim().isNotEmpty
        ? job.agentJustification.trim()
        : job.why.trim();

    return Material(
      color: Colors.transparent,
      child: InkWell(
        onTap: () => JobActionSheet.show(context, job),
        borderRadius: BorderRadius.circular(20),
        child: Container(
          padding: const EdgeInsets.all(18),
          decoration: BoxDecoration(
            color: brand.surface,
            borderRadius: BorderRadius.circular(20),
            border: Border.all(
              color: prominent
                  ? brand.accent.withValues(alpha: 0.55)
                  : brand.border,
              width: prominent ? 1.2 : 1,
            ),
            boxShadow: [
              BoxShadow(
                color: brand.shadow,
                blurRadius: 24,
                offset: const Offset(0, 10),
              ),
            ],
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                children: [
                  if (prominent)
                    Container(
                      padding: const EdgeInsets.symmetric(
                        horizontal: 9,
                        vertical: 4,
                      ),
                      decoration: BoxDecoration(
                        color: brand.accent,
                        borderRadius: BorderRadius.circular(99),
                      ),
                      child: Row(
                        mainAxisSize: MainAxisSize.min,
                        children: [
                          Icon(
                            Icons.bolt_rounded,
                            size: 12,
                            color: brand.onAccent,
                          ),
                          const SizedBox(width: 4),
                          Text(
                            matchLabel,
                            style: TextStyle(
                              fontSize: 10.5,
                              fontWeight: FontWeight.w900,
                              letterSpacing: 1.0,
                              color: brand.onAccent,
                            ),
                          ),
                        ],
                      ),
                    )
                  else ...[
                    Container(
                      width: 6,
                      height: 6,
                      decoration: BoxDecoration(
                        color: matchColor,
                        shape: BoxShape.circle,
                      ),
                    ),
                    const SizedBox(width: 7),
                    Text(
                      matchLabel,
                      style: TextStyle(
                        fontSize: 10.5,
                        fontWeight: FontWeight.w800,
                        letterSpacing: 1.3,
                        color: brand.textMuted,
                      ),
                    ),
                  ],
                  const Spacer(),
                  Icon(
                    Icons.more_horiz_rounded,
                    size: 20,
                    color: brand.textSoft,
                  ),
                ],
              ),
              const SizedBox(height: 10),
              Text(
                job.title,
                maxLines: 2,
                overflow: TextOverflow.ellipsis,
                style: TextStyle(
                  fontSize: 18,
                  fontWeight: FontWeight.w800,
                  letterSpacing: -0.4,
                  height: 1.2,
                  color: brand.ink,
                ),
              ),
              if (subtitle.isNotEmpty) ...[
                const SizedBox(height: 5),
                Text(
                  subtitle,
                  maxLines: 1,
                  overflow: TextOverflow.ellipsis,
                  style: TextStyle(
                    fontSize: 13,
                    fontWeight: FontWeight.w500,
                    letterSpacing: -0.1,
                    color: brand.textMuted,
                  ),
                ),
              ],
              if (why.isNotEmpty) ...[
                const SizedBox(height: 12),
                Container(
                  width: double.infinity,
                  padding: const EdgeInsets.symmetric(
                    horizontal: 11,
                    vertical: 9,
                  ),
                  decoration: BoxDecoration(
                    color: brand.surfaceMuted.withValues(alpha: 0.55),
                    borderRadius: BorderRadius.circular(12),
                    border: Border.all(
                      color: brand.border.withValues(alpha: 0.4),
                    ),
                  ),
                  child: Row(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Padding(
                        padding: const EdgeInsets.only(top: 1.5),
                        child: Icon(
                          Icons.auto_awesome_rounded,
                          size: 13,
                          color: brand.accent,
                        ),
                      ),
                      const SizedBox(width: 8),
                      Expanded(
                        child: Text.rich(
                          TextSpan(
                            style: TextStyle(
                              fontSize: 12.5,
                              fontWeight: FontWeight.w600,
                              letterSpacing: -0.1,
                              height: 1.35,
                              color: brand.textMuted,
                            ),
                            children: [
                              TextSpan(
                                text: 'Why it fits  ',
                                style: TextStyle(
                                  color: brand.textSoft,
                                  fontWeight: FontWeight.w800,
                                ),
                              ),
                              TextSpan(text: why),
                            ],
                          ),
                          maxLines: 3,
                          overflow: TextOverflow.ellipsis,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ],
          ),
        ),
      ),
    );
  }
}
